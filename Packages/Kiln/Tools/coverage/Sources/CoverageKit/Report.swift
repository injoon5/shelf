// Writes COVERAGE.md and coverage.json. Output is deterministic: the same SDK,
// manifest and rules give byte-identical files, so a diff shows real changes.

import Foundation

public struct SDKInfo: Codable, Equatable, Sendable {
    public var sdkVersion: String
    public var xcode: String
    public var interfaces: [String]
    public init(sdkVersion: String, xcode: String, interfaces: [String]) {
        self.sdkVersion = sdkVersion; self.xcode = xcode; self.interfaces = interfaces
    }
}

public enum Report {
    // MARK: - Names

    public static func display(_ s: SDKSymbol) -> String {
        switch s.kind {
        case .view, .content, .gesture, .type, .protocol: return s.name
        case .modifier: return s.owner.map { "\($0).\(s.name)" } ?? ".\(s.name)"
        case .style, .member: return "\(s.owner ?? "").\(s.name)"
        case .environment: return "\\.\(s.name)"
        case .wrapper, .macro: return "@\(s.name)"
        }
    }

    static func tag(_ s: SDKSymbol) -> String {
        var t: [String] = []
        if let v = s.introduced, Version(v) >= Version("18.0") { t.append(v.hasSuffix(".0") ? String(v.dropLast(2)) : v) }
        if s.deprecated { t.append("deprecated") }
        return t.isEmpty ? "" : " (\(t.joined(separator: ", ")))"
    }

    static func list(_ es: [CoverageEntry]) -> String {
        es.sorted { display($0.symbol).lowercased() < display($1.symbol).lowercased() }
            .map { "`\(display($0.symbol))`\(tag($0.symbol))\($0.status == .stub ? " (stub)" : "")" }
            .joined(separator: ", ")
    }

    static func roundName(_ r: Int?) -> String { r.map { "Round \($0)" } ?? "Outside the plan" }

    struct Tally { var total = 0, supported = 0, wontDo = 0, missing = 0 }

    static func tally(_ es: [CoverageEntry]) -> Tally {
        var t = Tally()
        for e in es where e.status != .plumbing {
            t.total += 1
            if e.status.isSupported { t.supported += 1 }
            if e.status.isDecidedOut { t.wontDo += 1 }
            if e.status.isMissing { t.missing += 1 }
        }
        return t
    }

    // MARK: - Markdown

    public static func markdown(_ r: CoverageResult, sdk: SDKInfo, families: FamilyRules, wontDo: WontDoList, manifestPath: String) -> String {
        var o: [String] = []
        let counted = r.entries.filter { $0.status != .plumbing }
        o.append("# Kiln coverage")
        o.append("")
        o.append("What Kiln runs, against every public view, modifier and style in the iOS SDK's SwiftUI, Charts and the `_*_SwiftUI` overlays (PLAN.md §1.9). "
                 + "Generated by `Packages/Kiln/Tools/coverage.sh`; don't edit it by hand. Run it after each round and after each Xcode update.")
        o.append("")
        o.append("- **SDK:** iOS \(sdk.sdkVersion), \(sdk.xcode)")
        o.append("- **Interfaces read:** \(sdk.interfaces.map { "`\($0)`" }.joined(separator: ", "))")
        o.append("- **Manifest:** `\(manifestPath)` (\(r.manifest.generator), \(r.manifest.symbols.count) symbols)")
        o.append("- **Rules:** `Tools/coverage/families.json`, `Tools/coverage/wont-do.json`")
        o.append("- **Machine-readable:** [`coverage.json`](coverage.json)")
        o.append("")
        if r.manifest.interim {
            o.append("> **Interim manifest.** §1.4's registry doesn't exist yet, so \"supported\" means \"Kiln 0.2.1's engine has a `case` for it\" "
                     + "(read from `KERenderer.swift`, `KEModifiers.swift` and `KEBuiltins.swift`). That says nothing about which overloads work, "
                     + "so this overstates support. These numbers are the **Round 1 baseline**. The registry's `kiln-manifest.json` replaces them (see `Docs/manifest.md`).")
            o.append("")
        }

        // Summary by round.
        o.append("## Summary")
        o.append("")
        o.append("A symbol is a view, a modifier (all overloads of one name, on one receiver), a style member, or one of the other kinds below. "
                 + "**Covered** is supported ÷ (symbols − won't do).")
        o.append("")
        o.append("| Round | Families | Symbols | Supported | Won't do / later | Missing | Covered |")
        o.append("|---|---|---:|---:|---:|---:|---:|")
        var roundKeys: [Int?] = Array(Set(r.families.map(\.round))).sorted { ($0 ?? 99) < ($1 ?? 99) }
        if roundKeys.isEmpty { roundKeys = [nil] }
        for rk in roundKeys {
            let fs = r.families.filter { $0.round == rk && $0.total > 0 }
            guard !fs.isEmpty else { continue }
            let t = fs.reduce(into: FamilyCount(family: "", round: rk)) { a, f in
                a.total += f.total; a.supported += f.supported; a.wontDo += f.wontDo; a.missing += f.missing
            }
            o.append("| \(roundName(rk)) | \(fs.count) | \(t.total) | \(t.supported) | \(t.wontDo) | \(t.missing) | \(t.percent)% |")
        }
        let all = tally(counted)
        let allPct = all.total - all.wontDo == 0 ? 100 : all.supported * 100 / (all.total - all.wontDo)
        o.append("| **All** | \(r.families.filter { $0.total > 0 }.count) | \(all.total) | \(all.supported) | \(all.wontDo) | \(all.missing) | \(allPct)% |")
        o.append("")

        // By kind.
        o.append("### By kind")
        o.append("")
        o.append("| Kind | Symbols | Supported | Won't do / later | Missing |")
        o.append("|---|---:|---:|---:|---:|")
        for k in SymbolKind.allCases {
            let t = tally(counted.filter { $0.symbol.kind == k })
            guard t.total > 0 else { continue }
            o.append("| \(k.plural) | \(t.total) | \(t.supported) | \(t.wontDo) | \(t.missing) |")
        }
        o.append("")

        // Families.
        o.append("## Families")
        o.append("")
        o.append("| Family | Round | Symbols | Supported | Won't do / later | Missing | Missing, new in iOS 26+ | Covered |")
        o.append("|---|---|---:|---:|---:|---:|---:|---:|")
        for f in r.families where f.total > 0 {
            o.append("| [\(f.family)](#\(anchor(f.family))) | \(f.round.map(String.init) ?? "—") | \(f.total) | \(f.supported) | \(f.wontDo) | \(f.missing) | \(f.missingNew) | \(f.percent)% |")
        }
        let empty = families.families.filter { f in !r.families.contains { $0.family == f.name && $0.total > 0 } }
        if !empty.isEmpty {
            o.append("")
            o.append("No SwiftUI symbols (their APIs are plain Swift types, which §1.4's type bridges cover): "
                     + empty.map { "\($0.name) (round \($0.round.map(String.init) ?? "—"))" }.joined(separator: ", ") + ".")
        }
        o.append("")

        // Per family: what's missing.
        o.append("## Missing, by family")
        o.append("")
        o.append("Versions are shown from iOS 18 on. **(stub)** means Kiln accepts the name but does nothing with it.")
        o.append("")
        for f in r.families where f.total > 0 {
            let es = r.entries(in: f.family)
            o.append("### \(f.family)")
            o.append("")
            if let fam = families.families.first(where: { $0.name == f.family }) {
                o.append("\(roundName(fam.round)). \(fam.summary)")
            }
            o.append("")
            o.append("\(f.supported) of \(f.total - f.wontDo) supported; \(f.missing) missing; \(f.wontDo) won't do or later.")
            o.append("")
            let missing = es.filter { $0.status.isMissing }
            if missing.isEmpty { o.append("Nothing missing."); o.append("") }
            for k in SymbolKind.allCases {
                let m = missing.filter { $0.symbol.kind == k }
                guard !m.isEmpty else { continue }
                o.append("- **\(k.plural)** (\(m.count)): \(list(m))")
            }
            let sup = es.filter { $0.status.isSupported }
            if !sup.isEmpty {
                o.append("")
                o.append("<details><summary>Supported (\(sup.count))</summary>")
                o.append("")
                o.append(list(sup))
                o.append("")
                o.append("</details>")
            }
            o.append("")
        }

        // Won't do and later.
        for status in [WontDoList.Status.wontDo, .later] {
            o.append(status == .wontDo ? "## Won't do" : "## Later")
            o.append("")
            o.append(status == .wontDo
                     ? "From `Tools/coverage/wont-do.json`. Each entry matches symbols by id, module, kind or name. A symbol that's supported stays supported even if an entry matches it (see Checks)."
                     : "On PLAN.md's Later list: not in Rounds 1–5, not ruled out. They don't count as missing.")
            o.append("")
            o.append("| What | Why | Symbols | Source |")
            o.append("|---|---|---:|---|")
            for w in wontDo.entries where w.status == status {
                let n = r.entries.filter { $0.wontDo == w.id }.count
                o.append("| \(w.what) | \(w.reason) | \(n) | \(w.source ?? "") |")
            }
            o.append("")
            for w in wontDo.entries where w.status == status {
                let es = r.entries.filter { $0.wontDo == w.id }
                guard !es.isEmpty else { continue }
                o.append("<details><summary>\(w.what) (\(es.count))</summary>")
                o.append("")
                o.append(list(es))
                o.append("")
                o.append("</details>")
                o.append("")
            }
        }

        // Unsorted.
        let unsorted = counted.filter { $0.family == FamilyRules.unsorted }
        o.append("## Unsorted")
        o.append("")
        if unsorted.isEmpty {
            o.append("Every symbol has a family.")
        } else {
            o.append("No rule in `families.json` matches these. Add one.")
            o.append("")
            o.append(list(unsorted))
        }
        o.append("")

        // Stubs.
        let stubs = counted.filter { $0.status == .stub }
        if !stubs.isEmpty {
            o.append("## Accepted but ignored")
            o.append("")
            o.append("Kiln accepts these so the code runs, but they have no effect. They count as missing.")
            o.append("")
            o.append(list(stubs))
            o.append("")
        }

        // Foundation and the standard library, against the corpus.
        if let corpus = r.manifest.corpus {
            o.append(contentsOf: corpusSection(corpus))
        }

        // Extras.
        o.append("## In the manifest, not in the SDK")
        o.append("")
        o.append("Kiln-only names (`UserShape`), Swift and Foundation types the engine constructs (`Date`, `URL`), and names that don't match an SDK symbol's id. "
                 + "They don't count here: Foundation and the standard library are counted against the corpus, above.")
        o.append("")
        o.append(r.extras.isEmpty ? "None." : r.extras.map { "`\($0.id)`" }.joined(separator: ", "))
        o.append("")

        // Checks.
        o.append("## Checks")
        o.append("")
        o.append("- **Won't-do entries that match nothing:** \(r.staleWontDo.isEmpty ? "none" : r.staleWontDo.map { "`\($0)`" }.joined(separator: ", "))")
        o.append("- **Supported, though a won't-do entry matches (supported wins):** \(r.conflicts.isEmpty ? "none" : r.conflicts.map { "`\($0.id)` (\($0.wontDo))" }.joined(separator: ", "))")
        let undeclared = families.undeclaredFamilies()
        o.append("- **Rules naming an undeclared family:** \(undeclared.isEmpty ? "none" : undeclared.joined(separator: ", "))")
        let plumbing = r.entries.filter { $0.status == .plumbing }
        o.append("- **Plumbing left out of every count:** \(plumbing.count) (`TupleView`, `ModifiedContent`, `_ConditionalContent` and the like; listed in `coverage.json`)")
        o.append("")
        return o.joined(separator: "\n")
    }

    static func anchor(_ s: String) -> String {
        s.lowercased().map { $0.isLetter || $0.isNumber ? String($0) : ($0 == " " || $0 == "-" ? "-" : "") }.joined()
    }

    // MARK: - JSON

    struct JSONReport: Codable {
        var schemaVersion = 1
        var sdk: SDKInfo
        var manifest: ManifestInfo
        var families: [FamilyCount]
        var staleWontDo: [String]
        var conflicts: [Conflict]
        var extras: [String]
        var entries: [CoverageEntry]
        var corpus: ManifestCorpus?
    }

    struct ManifestInfo: Codable {
        var path: String
        var generator: String
        var interim: Bool
        var symbols: Int
    }

    /// "Foundation and the standard library": the corpus's counts, and what doesn't pass.
    static func corpusSection(_ corpus: ManifestCorpus) -> [String] {
        var o: [String] = []
        o.append("## Foundation and the standard library")
        o.append("")
        o.append("The SDK lists above are SwiftUI's. Foundation, Combine and the standard library are counted against the corpus instead: "
                 + "everyday calls, each checked against the value compiled Swift prints (`Tests/Corpus`, PLAN.md §3, Round 2C; "
                 + "`Tools/corpus/oracle.py` writes the values). **Covered** is passing ÷ the entries run on the Mac; "
                 + "entries that need UIKit run on the simulator, in Shelf's tests.")
        o.append("")
        o.append("| Family | Section | Entries | Passing | Known gaps | Failing | Need iOS | Covered |")
        o.append("|---|---|---:|---:|---:|---:|---:|---:|")
        var total = (entries: 0, passing: 0, gaps: 0, failing: 0, ios: 0)
        for f in corpus.families {
            for s in f.sections {
                let ran = s.entries - s.ios
                let pct = ran == 0 ? 100 : s.passing * 100 / ran
                o.append("| \(f.name) | \(s.name) | \(s.entries) | \(s.passing) | \(s.gaps.count) | \(s.failing.count) | \(s.ios) | \(pct)% |")
                total.entries += s.entries; total.passing += s.passing; total.gaps += s.gaps.count
                total.failing += s.failing.count; total.ios += s.ios
            }
        }
        let ran = total.entries - total.ios
        o.append("| **All** | | \(total.entries) | \(total.passing) | \(total.gaps) | \(total.failing) | \(total.ios) | \(ran == 0 ? 100 : total.passing * 100 / ran)% |")
        o.append("")
        let missing = corpus.families.flatMap { f in f.sections.flatMap { s in
            s.gaps.map { "- \(f.name) · \(s.name): `\($0)` (a known gap)" } + s.failing.map { "- \(f.name) · \(s.name): `\($0)` (**fails**)" }
        } }
        o.append("### Not passing")
        o.append("")
        o.append(contentsOf: missing.isEmpty ? ["Nothing."] : missing)
        o.append("")
        return o
    }

    public static func json(_ r: CoverageResult, sdk: SDKInfo, manifestPath: String) throws -> Data {
        let rep = JSONReport(sdk: sdk,
                             manifest: ManifestInfo(path: manifestPath, generator: r.manifest.generator, interim: r.manifest.interim,
                                                    symbols: r.manifest.symbols.count),
                             families: r.families, staleWontDo: r.staleWontDo, conflicts: r.conflicts,
                             extras: r.extras.map(\.id), entries: r.entries.sorted { $0.symbol.id < $1.symbol.id },
                             corpus: r.manifest.corpus)
        let e = JSONEncoder()
        e.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try e.encode(rep) + Data("\n".utf8)
    }
}
